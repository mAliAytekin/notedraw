  const before = await workspace(page), original = (await panel.boundingBox())!
  const camera = await page.evaluate(() => window.__phase0!.editor.getCamera())
  const heading = (await handle.boundingBox())!
  await page.mouse.move(heading.x + 100, heading.y + 10)
  await page.mouse.down(); await page.mouse.move(heading.x - 150, heading.y + 40, { steps: 10 }); await page.mouse.up()
  const moved = (await panel.boundingBox())!
  expect(moved.x).toBeCloseTo(original.x - 250, 0)
  expect(moved.y).toBeCloseTo(original.y + 30, 0)
  expect(await page.evaluate(() => window.__phase0!.editor.getCamera())).toEqual(camera)
  expect((await workspace(page)).notes).toEqual(before.notes)
  expect((await workspace(page)).boards.map(board => board.document)).toEqual(before.boards.map(board => board.document))
