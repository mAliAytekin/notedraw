test('dragging an existing note creates a card at the drop position without copying note contents', async ({ page }) => {
  await create(page, 'Board', 'Boş board')
  const note = page.getByRole('group', { name: 'Not: Bilinç Problemi', exact: true }).locator('.tree-label')
  const canvas = page.getByRole('region', { name: 'Bilgi tuvali' })
  const box = (await canvas.boundingBox())!
  const data = await page.evaluateHandle(() => new DataTransfer())
  await note.dispatchEvent('dragstart', { dataTransfer: data })
  await canvas.dispatchEvent('dragover', { dataTransfer: data, clientX: box.x + 260, clientY: box.y + 220 })
  await canvas.dispatchEvent('drop', { dataTransfer: data, clientX: box.x + 260, clientY: box.y + 220 })
  await expect(card(page)).toHaveCount(1)
  const state = await workspace(page)
  expect(state.notes).toHaveLength(2)
  const shape = Object.values(state.boards.find(board => board.boardId === state.activeBoardId)!.document.store).find(record => record.typeName === 'shape')!
  expect(shape).toMatchObject({ type: 'markdown-card', props: { noteId: 'note:bilinc' } })
  await data.dispose()
})

