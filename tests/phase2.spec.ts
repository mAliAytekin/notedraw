import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { pdfFixture } from './helpers/pdf'

const accel = process.platform === 'darwin' ? 'Meta' : 'Control'
const card = (page: Page) => page.getByTestId('markdown-card').first()
const source = (page: Page) => page.getByRole('textbox', { name: 'Markdown kaynak', exact: true })
async function ready(page: Page) {
  await expect.poll(() => page.evaluate(() => !!window.__phase0)).toBe(true)
  await expect(page.locator('.save-indicator[data-state="saved"]')).toBeVisible()
}
async function workspace(page: Page) { return page.evaluate(() => window.__phase0!.runtime.captureWorkspace(window.__phase0!.runtime.saver!.getStatus().revision)) }
async function create(page: Page, kind: 'Klasör' | 'Board' | 'Not', name: string) {
  await page.getByRole('button', { name: `+ ${kind}`, exact: true }).click()
  await page.getByLabel('Öğe adı', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Kaydet', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function board(page: Page, name: string) {
  await page.getByRole('group', { name: `Board: ${name}`, exact: true }).getByRole('button', { name, exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__phase0!.runtime.activeBoard.title)).toBe(name)
  await ready(page)
}
async function editCard(page: Page, markdown: string) {
  const box = (await card(page).boundingBox())!
  await page.mouse.dblclick(box.x + 90, box.y + 75)
  await page.getByRole('tab', { name: 'Kaynak', exact: true }).click()
  await source(page).fill(markdown)
}
async function downloadWorkspace(page: Page) {
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Workspace yedeği indir', exact: true }).click()
  return JSON.parse(await readFile((await (await download).path())!, 'utf8'))
}
async function upload(page: Page, value: unknown) {
  await page.getByLabel('Board yedeği seç').setInputFiles({ name: 'workspace.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value)) })
}
async function openPdf(page: Page, name = 'reading.pdf', data = pdfFixture()) {
  await page.getByLabel('PDF dosyası seç').setInputFiles({ name, mimeType: 'application/pdf', buffer: data })
  await expect(page.getByLabel('PDF okuma paneli')).toBeVisible()
  await expect(page.locator('.textLayer')).toContainText('Qualia and consciousness')
  await expect(page.getByText('PDF hazırlanıyor…', { exact: true })).toHaveCount(0)
}
async function resizePdf(page: Page, edge: string, dx: number, dy: number) {
  const handle = page.getByRole('button', { name: `PDF panelini ${edge} boyutlandır`, exact: true })
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2 + dy, { steps: 8 })
  await page.mouse.up()
}

