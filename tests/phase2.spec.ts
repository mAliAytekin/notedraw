test('queued rapid board switches wait for a slow commit and keep editor changes safe', async ({ page }) => {
  await create(page, 'Board', 'B board'); await create(page, 'Board', 'C board')
  await board(page, 'Kavram haritası')
  await page.evaluate(() => {
    const runtime = window.__phase0!.runtime, adapter = runtime.adapter, save = adapter.save.bind(adapter)
    let release!: () => void
    const held = new Promise<void>(resolve => { release = resolve })
    ;(window as any).__releaseCommit = release
    adapter.save = async value => { await held; return save(value) }
  })
  await editCard(page, '# Hızlı geçişte korunacak metin')
  await page.evaluate(() => {
    const runtime = window.__phase0!.runtime, boards = runtime.workspace.get().boards
    ;(window as any).__switchResult = 'pending'
    void Promise.all([runtime.switchBoard(boards.find(board => board.title === 'B board')!.boardId), runtime.switchBoard(boards.find(board => board.title === 'C board')!.boardId)])
      .then(() => { (window as any).__switchResult = 'done' })
      .catch(error => { (window as any).__switchResult = error.message })
  })
  await expect(page.getByRole('button', { name: '+ Yeni Markdown Kartı', exact: true })).toBeDisabled()
  expect(await page.evaluate(() => window.__phase0!.runtime.activeBoard.title)).toBe('Kavram haritası')
  await page.evaluate(() => (window as any).__releaseCommit())
  await expect.poll(() => page.evaluate(() => (window as any).__switchResult)).toBe('done')
  await board(page, 'Kavram haritası')
  await expect(card(page)).toContainText('Hızlı geçişte korunacak metin')
  await page.reload(); await ready(page)
  await expect(card(page)).toContainText('Hızlı geçişte korunacak metin')
})
